/**
 * التوحيد الثلاثي كما ينص التوثيق:
 *   1. تشذيب المسافات الطرفية
 *   2. اختصار المسافات المتكررة إلى واحدة
 *   3. تحويل الأرقام العربية الهندية إلى لاتينية
 *
 * تشمل الخطوة الثالثة المجموعتين معاً:
 *   ٠-٩  العربية الهندية      U+0660..U+0669
 *   ۰-۹  الفارسية/الأردية     U+06F0..U+06F9
 * لوحة المفاتيح العربية على الهواتف تُنتج الأولى، وبعض
 * لوحات المفاتيح تُنتج الثانية — والمستخدم لا يميّز بينهما.
 *
 * \s في نمط اختصار المسافات بعلامة u ليلتقط المسافات غير
 * الكاسرة والمسافات العربية التي تُلصَق عند النسخ من مستند.
 */
function normalizeVehicleId(?string $value): ?string {
    if ($value === null) return null;

    $digits = [
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
    ];
    $value = strtr($value, $digits);

    // الاختصار قبل التشذيب: سلسلة من المسافات وحدها تصير مسافة ثم تُشذَّب
    $value = preg_replace('/\s+/u', ' ', $value);

    return trim($value);
}

/** يُرجع NULL للسلسلة الفارغة — القيمة الفارغة تجتاز قيد CHECK في القاعدة. */
function normalizeVehicleIdOrNull(?string $value): ?string {
    $v = normalizeVehicleId($value);
    return ($v === null || $v === '') ? null : $v;
}
